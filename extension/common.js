export const DEFAULTS = {
  apiBase: "http://127.0.0.1:8787",
  apiToken: "",
  // Docker is optional. Off means browser-only: nothing to install, nothing
  // to mount, and no reason to even probe localhost.
  useContainer: false,
  // absolute path the native helper moves finished courses to; "" = leave them
  // in the browser download folder
  nativeTarget: "",
  // how many files download at once in browser mode (plain + extras jobs)
  parallel: 3,
};

export async function getSettings() {
  const stored = await chrome.storage.local.get(["apiBase", "apiToken", "useContainer", "nativeTarget", "parallel"]);
  return { ...DEFAULTS, ...stored };
}

export async function setSettings(patch) {
  await chrome.storage.local.set(patch);
}

export async function api(path, { method = "GET", body } = {}) {
  const { apiBase, apiToken } = await getSettings();
  const headers = {};
  if (apiToken) headers["X-Api-Token"] = apiToken;
  if (body !== undefined) headers["Content-Type"] = "application/json";

  let res;
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 20000);
  try {
    res = await fetch(apiBase.replace(/\/+$/, "") + path, {
      method,
      headers,
      body: body === undefined ? undefined : JSON.stringify(body),
      signal: controller.signal,
    });
  } catch {
    // a hung request here would freeze the popup's refresh loop
    throw new Error(`cannot reach ${apiBase} — is the container running?`);
  } finally {
    clearTimeout(timer);
  }

  const text = await res.text();
  let data = null;
  if (text) {
    try {
      data = JSON.parse(text);
    } catch {
      data = { raw: text };
    }
  }
  if (res.status === 401) {
    throw new Error(
      apiToken
        ? "API token rejected. Open Settings and re-paste UD_API_TOKEN from the repo's .env."
        : "No API token saved yet. Open Settings and paste UD_API_TOKEN from the repo's .env."
    );
  }
  if (!res.ok) throw new Error((data && data.error) || `HTTP ${res.status}`);
  return data;
}

// Mirrors extract_course_name() in main.py so we send a URL it can parse.
const COURSE_RE = /^https?:\/\/([A-Za-z0-9-]+)\.udemy\.com\/course(?:\/draft)*\/([A-Za-z0-9_-]+)/i;

export function parseCourseUrl(url) {
  const m = COURSE_RE.exec(url || "");
  if (!m) return null;
  const [, portal, slug] = m;
  return {
    portal,
    slug,
    host: `${portal}.udemy.com`,
    normalized: `https://${portal}.udemy.com/course/${slug}/learn/`,
  };
}

// main.py accepts the bearer as the access_token cookie value (see main.py:1864).
export async function getBearer(host) {
  for (const h of new Set([host, "www.udemy.com"].filter(Boolean))) {
    try {
      const c = await chrome.cookies.get({ url: `https://${h}/`, name: "access_token" });
      if (c && c.value) return c.value;
    } catch {
      /* host not permitted or no cookie; try the next one */
    }
  }
  return null;
}

export async function exportCookiesTxt() {
  const cookies = await chrome.cookies.getAll({ domain: "udemy.com" });
  // Python's MozillaCookieJar discards cookies whose expiry is 0, so session
  // cookies get a short synthetic lifetime instead.
  const synthetic = Math.floor(Date.now() / 1000) + 86400;
  const lines = ["# Netscape HTTP Cookie File", "# generated by Udemy Downloader Bridge", ""];
  for (const c of cookies) {
    const domain = c.hostOnly ? c.domain : c.domain.startsWith(".") ? c.domain : `.${c.domain}`;
    const expiry = c.session || !c.expirationDate ? synthetic : Math.floor(c.expirationDate);
    lines.push(
      [
        domain,
        c.hostOnly ? "FALSE" : "TRUE",
        c.path || "/",
        c.secure ? "TRUE" : "FALSE",
        expiry,
        c.name,
        c.value,
      ].join("\t")
    );
  }
  return `${lines.join("\n")}\n`;
}

export const PREFS_KEY = "formPrefs";
export const DEST_KEY = "destPath";

/** Record a course's absolute folder so the offline player can build file://
 *  URLs. Shared by the background worker and the download runners. */
export async function setCourseRoot(courseTitle, root) {
  if (!courseTitle || !root) return;
  const stored = await chrome.storage.local.get("courses");
  const courses = stored.courses || {};
  if (!courses[courseTitle] || courses[courseTitle].root === root) return;
  courses[courseTitle].root = root;
  await chrome.storage.local.set({ courses });
}

export async function getPrefs() {
  const stored = await chrome.storage.local.get([PREFS_KEY, DEST_KEY]);
  return { prefs: stored[PREFS_KEY] || {}, dest: stored[DEST_KEY] || "" };
}

const BOOL_KEYS = [
  "download_captions", "download_assets", "download_quizzes", "skip_lectures",
  "keep_vtt", "skip_hls", "subscription_course", "id_as_course_name",
  "continue_lecture_numbers", "save_to_file", "load_from_file",
  "use_h265", "use_nvenc",
];

// Single source of truth for the request body, shared by the popup and the
// in-page button so the two can never drift apart.
export function jobBodyFromPrefs(prefs, extras) {
  const body = {
    course_url: extras.courseUrl,
    bearer: extras.bearer || "",
    log_level: prefs.log_level || "INFO",
  };
  if (prefs.quality && prefs.quality !== "best") body.quality = Number(prefs.quality);
  if (prefs.concurrent) body.concurrent_downloads = Number(prefs.concurrent);
  if (prefs.chapter) body.chapter = String(prefs.chapter).trim();
  for (const key of BOOL_KEYS) if (prefs[key]) body[key] = true;
  if (body.download_captions && prefs.lang) body.lang = String(prefs.lang).trim();
  if (body.use_h265) {
    body.h265_crf = Number(prefs.h265_crf || 28);
    body.h265_preset = prefs.h265_preset || "medium";
  }
  if (extras.cookiesTxt) {
    // main.py:405 is bearer-OR-cookies, never both
    body.cookies_txt = extras.cookiesTxt;
    body.bearer = "";
  }
  if (extras.dest !== undefined) body.dest = extras.dest;
  if (extras.infoOnly) body.info = true;
  return body;
}

/** Health payload if the container is reachable, else null. Short timeout so a
 *  missing container doesn't stall the popup. */
export async function containerAvailable(timeoutMs = 2500) {
  const { apiBase } = await getSettings();
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  try {
    const res = await fetch(`${apiBase.replace(/\/+$/, "")}/api/health`, {
      signal: controller.signal,
    });
    return res.ok ? await res.json() : null;
  } catch {
    return null;
  } finally {
    clearTimeout(timer);
  }
}

/** data: URL for generated text, UTF-8 safe (btoa alone is latin-1 only). */
function textToDataUrl(text, mime) {
  const bytes = new TextEncoder().encode(text);
  let bin = "";
  for (let i = 0; i < bytes.length; i += 0x8000) {
    bin += String.fromCharCode(...bytes.subarray(i, i + 0x8000));
  }
  return `data:${mime};base64,${btoa(bin)}`;
}

/**
 * Turn each quiz in the plan into a self-contained interactive HTML file —
 * upstream's own quiz player (practice/exam modes, timer, saved attempts),
 * fed the same JSON shape process_normal_quiz() builds (main.py:1739).
 */
async function prepareQuizzes(plan, portal) {
  const quizzes = plan.chapters.flatMap((c) => c.lectures).filter((l) => l.kind === "quiz");
  if (!quizzes.length) return;

  const template = await (await fetch(chrome.runtime.getURL("quiz_template.html"))).text();

  for (const quiz of quizzes) {
    if (quiz.quizType === "coding-exercise") {
      quiz.unsupported = "coding exercise";
      continue;
    }
    try {
      const assessments = await fetchQuizAssessments(portal, quiz.quizId);
      if (assessments.some((a) => a.assessment_type === "coding-problem")) {
        quiz.unsupported = "coding exercise";
        continue;
      }
      const data = {
        id: quiz.quizId,
        title: quiz.quizTitle,
        description: quiz.quizDescription,
        pass_score: quiz.passPercent,
        assessments,
      };
      const html = template
        .replace("%%TITLE%%", quiz.quizTitle)
        // \\u003c keeps a "</script>" inside quiz content from ending the tag
        .replace("%%QUIZ_JSON%%", JSON.stringify(data).replace(/</g, "\\u003c"));
      quiz.dataUrl = textToDataUrl(html, "text/html;charset=utf-8");
    } catch (err) {
      quiz.unsupported = err.message;
    }
  }
}

export const COURSES_KEY = "courses";

/** Persist the course structure so the player can render it like Udemy's
 *  sidebar. `rel` paths are relative to the course folder itself. */
async function saveCourseManifest(plan, opts) {
  const sections = plan.chapters.map((ch) => ({
    title: ch.title,
    items: ch.lectures
      .filter((l) => l.kind === "video" || (l.kind === "quiz" && l.dataUrl))
      .map((l) => ({
        name: l.name,
        kind: l.kind,
        rel: `${ch.title}/${l.name}${l.kind === "quiz" ? ".html" : ".mp4"}`,
        drm: !!l.drm,
        // only the caption language(s) actually downloaded (matches the lang
        // filter), so the player doesn't probe — and 404 on — every language
        captions: (l.captions || [])
          .map((c) => c.lang)
          .filter((lang) => {
            const want = (opts.lang || "en").toLowerCase();
            return want === "all" || String(lang).toLowerCase().split("_")[0] === want;
          }),
        // downloadable attachments for this lecture (shown in the player);
        // external links keep their URL, files point at the on-disk sibling
        resources: opts.assets
          ? (l.assets || []).map((a) => a.externalUrl
            ? { name: a.name, externalUrl: a.externalUrl }
            : { name: a.name, rel: `${ch.title}/${l.name} - ${a.name}` })
          : [],
      })),
  })).filter((s) => s.items.length);

  const stored = await chrome.storage.local.get(COURSES_KEY);
  const courses = stored[COURSES_KEY] || {};
  const prev = courses[plan.courseTitle] || {};
  courses[plan.courseTitle] = {
    id: plan.courseTitle,
    title: plan.courseTitle,
    root: prev.root || null,
    destSub: opts.dest || "",
    sections,
    savedAt: Date.now(),
  };
  await chrome.storage.local.set({ [COURSES_KEY]: courses });
}

/** Build and start a download entirely in the browser, no container. */
async function queueLocal({ courseUrl, infoOnly }) {
  const parsed = parseCourseUrl(courseUrl);
  if (!parsed) throw new Error("Not a Udemy course URL.");

  const course = await findCourse(parsed.portal, parsed.slug);
  const items = await fetchCurriculum(parsed.portal, course.id);
  const { prefs: planPrefs } = await getPrefs();
  const plan = buildPlan(items, course.title, {
    idAsName: !!planPrefs.id_as_course_name,
    courseId: course.id,
    continueNumbers: planPrefs.continue_lecture_numbers !== false,
    quality: planPrefs.quality,
  });

  if (infoOnly) {
    // probe one lecture's HLS ladder: decides whether 1080p is reachable
    // locally without a muxer
    let hls = null;
    const sample = plan.chapters
      .flatMap((c) => c.lectures)
      .find((l) => l.kind === "video" && !l.drm && l.hlsUrl);
    if (sample) {
      try {
        hls = await probeHls(sample.hlsUrl);
      } catch (err) {
        hls = { error: err.message };
      }
    }
    return {
      mode: "local",
      id: "local-info",
      plan: plan.stats,
      courseTitle: plan.courseTitle,
      hls,
    };
  }

  const { prefs, dest } = await getPrefs();
  const { nativeTarget } = await getSettings();
  const opts = {
    // relative to the browser's download folder, not /library
    // a subfolder of the download location, so ordinary downloads are untouched
    dest: dest || "Courses",
    captions: !!prefs.download_captions,
    assets: !!prefs.download_assets,
    quizzes: !!prefs.download_quizzes,
    keepVtt: !!prefs.keep_vtt,
    skipLectures: !!prefs.skip_lectures,
    chapter: prefs.chapter,
    lang: prefs.lang,
    // skip files already on disk in the destination (by name)
    skipExisting: prefs.skip_existing !== false,
    nativeTarget: nativeTarget || "",
  };

  if (opts.quizzes) await prepareQuizzes(plan, parsed.portal);

  // Course manifest for the built-in player: structure now, absolute root
  // filled in by the background worker once a real file lands on disk.
  await saveCourseManifest(plan, opts);

  opts.courseTitle = plan.courseTitle;

  // skip_hls forces the progressive path (no HLS/transmux), honoring the toggle.
  if (prefs.hd && !opts.skipLectures && !prefs.skip_hls) {
    // always under the download folder; the native helper moves it after
    // videos go down the HLS/transmux path; captions and assets are plain files,
    // so they still ride the browser's download manager
    const hd = await startHdJob(plan, {
      ...opts,
      maxHeight: Number(prefs.quality) || 1080, // honor the Quality cap (else 1080p)
      concurrency: Math.max(Number(prefs.hd_lanes) || 0, 2),
    });
    if (opts.captions || opts.assets || opts.quizzes) {
      // may be null when the filtered chapters contain no extras at all
      await startLocalJob(plan, { ...opts, skipLectures: true });
    }
    return hd;
  }
  const job = await startLocalJob(plan, opts);
  if (!job) {
    throw new Error(
      "Nothing to download with these settings — check the chapter filter and the Include boxes."
    );
  }
  return job;
}

/**
 * Container only when the user asked for it AND it answers. Otherwise the
 * browser does the work. Never probes localhost when Docker is switched off.
 */
export async function queueAuto({ courseUrl, infoOnly = false }) {
  const { useContainer } = await getSettings();
  if (useContainer) {
    const health = await containerAvailable();
    if (health) return { ...(await queueJob({ courseUrl, infoOnly })), mode: "container" };
  }
  return queueLocal({ courseUrl, infoOnly });
}

/** Queue a job using the saved popup settings. Returns the created job. */
export async function queueJob({ courseUrl, infoOnly = false }) {
  const parsed = parseCourseUrl(courseUrl);
  if (!parsed) throw new Error("Not a Udemy course URL.");

  const { prefs, dest } = await getPrefs();
  const health = await api("/api/health");

  const extras = { courseUrl: parsed.normalized, infoOnly };
  if (health.library && health.library.mounted) extras.dest = dest;

  if (prefs.send_cookies) {
    extras.cookiesTxt = await exportCookiesTxt();
  } else {
    extras.bearer = await getBearer(parsed.host);
    if (!extras.bearer) {
      throw new Error("Not signed in to Udemy in this browser, and cookie mode is off.");
    }
  }
  return api("/api/jobs", { method: "POST", body: jobBodyFromPrefs(prefs, extras) });
}

/**
 * Every open Udemy course tab, active one first, deduped by course.
 * Returns a list so callers can disambiguate instead of silently picking the
 * first tab in an arbitrary order.
 */
export async function findCourseTabs() {
  const [active] = await chrome.tabs.query({ active: true, currentWindow: true });
  const all = await chrome.tabs.query({ url: ["*://*.udemy.com/course/*"] });

  const ordered = [];
  if (active && parseCourseUrl(active.url)) ordered.push(active);
  ordered.push(...all);

  const seen = new Set();
  const out = [];
  for (const tab of ordered) {
    const parsed = parseCourseUrl(tab.url);
    if (!parsed || seen.has(parsed.normalized)) continue;
    seen.add(parsed.normalized);
    out.push({
      id: tab.id,
      title: tab.title || parsed.slug,
      slug: parsed.slug,
      host: parsed.host,
      url: parsed.normalized,
      isActive: !!(active && tab.id === active.id),
    });
  }
  return out;
}

export function shortToken(token) {
  if (!token) return "";
  return token.length <= 12 ? token : `${token.slice(0, 6)}…${token.slice(-4)}`;
}
